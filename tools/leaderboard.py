"""Render LEADERBOARD.md from results/*/*.score.json. Generated, never hand-edited."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(cell: dict | None) -> str:
    if not cell or "mean" not in cell:
        return "—"
    lo, hi = cell["ci95"]
    return f"{cell['mean']:.3f} [{lo:.3f}, {hi:.3f}]"


def main() -> int:
    rows = []
    for sj in sorted(ROOT.glob("results/*/*.score.json")):
        score = json.loads(sj.read_text(encoding="utf-8"))
        sysf = sj.with_name(sj.name.replace(".score.json", ".system.json"))
        system = json.loads(sysf.read_text(encoding="utf-8")) if sysf.is_file() else {}
        rows.append((sj, score, system))
    out = ["# Leaderboard", "",
           "Generated by `tools/leaderboard.py` from `results/*/*.score.json`; every number is the",
           "released grader's. Headline: `premise_necessary` subset (RULES §6). Intervals are 95%",
           "bootstrap over items. `solved` is the fraction of items solved by any of the n samples.", ""]
    for split in ("test", "dev"):
        sel = [r for r in rows if r[1].get("split") == split]
        if not sel:
            continue
        out += [f"## {split}", "",
                "| system | track | K | n | budget | exposure | pass@1 (necessary) | pass@8 | pass@32 | solved (necessary) | solved (all) | items |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for sj, sc, sy in sorted(sel, key=lambda r: -((r[1]["subsets"]["premise_necessary"].get("solved_any")) or 0)):
            h = sc["subsets"]["premise_necessary"]
            al = sc["subsets"]["all"]
            out.append("| {name} | {track} | {k} | {n} | {budget} | {exp} | {p1} | {p8} | {p32} | {sn} | {sa} | {ni} |".format(
                name=sy.get("name", sj.parent.name), track=sy.get("track", "?"), k=sc["k_base"],
                n=sc["n_samples"], budget=sy.get("budget", "—"), exp=sy.get("exposure", "—"),
                p1=fmt(h.get("pass@1")), p8=fmt(h.get("pass@8")), p32=fmt(h.get("pass@32")),
                sn=f"{h['solved_any']:.3f}" if h.get("solved_any") is not None else "—",
                sa=f"{al['solved_any']:.3f}" if al.get("solved_any") is not None else "—",
                ni=sc["n_items"]))
        out.append("")
    (ROOT / "LEADERBOARD.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
