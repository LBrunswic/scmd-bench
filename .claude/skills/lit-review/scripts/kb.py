def cmd_chain(a):
    """Backward (references) and forward (cited-by) snowballing from the selected
    seeds. Candidates are ranked by how many seeds link to them — a work cited by
    five of your trusted papers matters more than one cited by one."""
    kb = KB(a.kb).require()
    refs = kb.load()
    seeds = _select(refs, a)
    if not seeds:
        die("no seeds match the selection")
    have = {r.get("openalex") for r in refs if r.get("openalex")}
    votes: dict[str, set[str]] = {}
    for s in seeds:
        oid = s.get("openalex")
        if not oid:
            got = resolve(doi=s.get("doi"), arxiv=s.get("arxiv"), title=None if (s.get("doi") or s.get("arxiv")) else s["title"])
            oid = got and got.get("openalex")
            if oid:
                s["openalex"] = oid
        if not oid:
            got = resolve(title=s["title"])
            oid = got and got.get("openalex")
            if oid:
                s["openalex"] = oid
        back, fwd = [], []
        if oid and a.direction in ("both", "backward"):
            w = _oa_work(oid)
            back = [r.rsplit("/", 1)[-1] for r in (w or {}).get("referenced_works", [])]
        if oid and a.direction in ("both", "forward"):
            data = get_json(f"https://api.openalex.org/works?filter=cites:{oid}&per-page=200&sort=cited_by_count:desc")
            fwd = [w["id"].rsplit("/", 1)[-1] for w in (data or {}).get("results", [])]
        # OpenAlex has no reference list for many arXiv-only records; Semantic Scholar often does
        src = "openalex"
        if (not back and a.direction != "forward") or (not fwd and a.direction != "backward"):
            s2b, s2f = _s2_links(s, a.direction)
            if not back and s2b:
                back, src = s2b, "openalex+s2"
            if not fwd and s2f:
                fwd, src = s2f, "openalex+s2"
        if not oid and not back and not fwd:
            print(f"  --   {s['key']}: not found in OpenAlex or Semantic Scholar, skipped")
            continue
        for w in back + fwd:
            votes.setdefault(w, set()).add(s["key"])
        print(f"  seed {s['key']}: {len(back)} refs, {len(fwd)} citing ({src})")
    ranked = sorted(((k, v) for k, v in votes.items() if k not in have), key=lambda kv: -len(kv[1]))
    ranked = [kv for kv in ranked if len(kv[1]) >= a.min_votes][: a.limit]
    recs = []
    for i in range(0, len(ranked), 50):
        chunk = ranked[i:i + 50]
        data = get_json("https://api.openalex.org/works?per-page=50&filter=openalex:" + "|".join(k for k, _ in chunk))
        by = {w["id"].rsplit("/", 1)[-1]: w for w in (data or {}).get("results", [])}
        for k, v in chunk:
            if k in by:
                rec = from_openalex(by[k])
                rec["_votes"] = sorted(v)
                recs.append(rec)
    new = []
    taken = {r["key"] for r in refs}
    for rec in recs:
        voters = rec.pop("_votes")
        rec["found_by"] = [f"chain:{a.direction}:{','.join(voters)}"]
        rec["chain_votes"] = len(voters)
        if find_dup(refs, rec):
            merge(find_dup(refs, rec), rec)
            continue
        enrich(rec)
        rec["round"] = a.to_round
        rec["key"] = make_key(rec, taken)
        taken.add(rec["key"])
        rec["trust"]["prior"], rec["trust"]["factors"] = trust_prior(rec)
        refs.append(rec)
        new.append(rec)
    kb.save(refs)
    kb.log_search({"round": a.to_round, "source": "chain", "query": f"{a.direction} from {len(seeds)} seeds",
                   "hits": len(votes), "new": len(new), "date": dt.date.today().isoformat(),
                   "keys": [r["key"] for r in new]})
    print(f"{len(votes)} linked works, {len(new)} new candidates (min {a.min_votes} seed links)")
    for r in sorted(new, key=lambda r: -r["chain_votes"]):
        print(f"  votes={r['chain_votes']:<2} " + _row(r))


def _s2_links(r: dict, direction: str) -> tuple[list[str], list[str]]:
    """References / citations from Semantic Scholar, mapped to OpenAlex ids."""
    pid = (f"arXiv:{r['arxiv']}" if r.get("arxiv") else f"DOI:{r['doi']}" if r.get("doi") else None)
    if not pid:
        return [], []
    out = []
    for rel, field in (("references", "citedPaper"), ("citations", "citingPaper")):
        if (rel == "references" and direction == "forward") or (rel == "citations" and direction == "backward"):
            out.append([])
            continue
        data = get_json(f"https://api.semanticscholar.org/graph/v1/paper/{urllib.parse.quote(pid)}/{rel}"
                        f"?fields=externalIds&limit=500")
        time.sleep(1.5)
        dois = []
        for item in (data or {}).get("data", []):
            ext = (item.get(field) or {}).get("externalIds") or {}
            if ext.get("DOI"):
                dois.append(norm_doi(ext["DOI"]))
            elif ext.get("ArXiv"):
                dois.append(f"10.48550/arxiv.{norm_arxiv(ext['ArXiv'])}")
        out.append(_oa_ids_for_dois(dois))
    return out[0], out[1]


def _oa_ids_for_dois(dois: list[str]) -> list[str]:
    ids = []
    for i in range(0, len(dois), 50):
        chunk = dois[i:i + 50]
        data = get_json("https://api.openalex.org/works?per-page=50&select=id&filter=doi:" + "|".join(chunk))
        ids += [w["id"].rsplit("/", 1)[-1] for w in (data or {}).get("results", [])]
    return ids


