def cmd_set(a):
    kb = KB(a.kb).require()
    refs = kb.load()
    by = {r["key"]: r for r in refs}
    targets = [by[k] for k in a.keys if k in by]
    missing = [k for k in a.keys if k not in by]
    if missing:
        die(f"unknown keys: {missing}")
    for assign in a.assign:
        field, _, val = assign.partition("=")
        try:
            v = json.loads(val)
        except json.JSONDecodeError:
            v = val
        for r in targets:
            if field == "status" and v not in STATUSES:
                die(f"status must be one of {STATUSES}")
            if field in ("tier", "rationale"):
                if field == "tier" and v not in TIERS:
                    die("tier must be 1..5")
                r["trust"][field] = v
            elif field.startswith("factor."):
                r["trust"]["factors"][field[7:]] = v
            elif field == "tag":
                r.setdefault("tags", []).append(v)
            else:
                r[field] = v
    kb.save(refs)
    print(f"updated {len(targets)} record(s)")


def cmd_fetch(a):
    kb = KB(a.kb).require()
    refs = kb.load()
    for r in _select(refs, a):
        pdf = kb.root / "pdf" / f"{r['key']}.pdf"
        if not pdf.exists() and not r.get("arxiv"):
            r["arxiv"] = arxiv_by_title(r["title"])
            if r["arxiv"]:
                print(f"  ..   {r['key']}: found arXiv copy {r['arxiv']} by exact title")
        if not pdf.exists():
            urls = [u for u in (f"https://arxiv.org/pdf/{r['arxiv']}" if r.get("arxiv") else None,
                                r.get("pdf_url")) if u]
            for u in urls:
                data = http_get(u, accept="application/pdf", binary=True)
                if data and data[:5] == b"%PDF-":
                    pdf.write_bytes(data)
                    break
                time.sleep(1)
        if pdf.exists():
            txt = kb.root / "text" / f"{r['key']}.txt"
            if not txt.exists():
                subprocess.run(["pdftotext", "-q", str(pdf), str(txt)], check=False)
            r["pdf"] = f"pdf/{pdf.name}"
            r["text"] = f"text/{txt.name}" if txt.exists() else None
            print(f"  ok   {r['key']}  ({pdf.stat().st_size // 1024} KiB)")
        else:
            print(f"  --   {r['key']}  no open-access PDF found — note must name where the text was read")
    kb.save(refs)


def _qnorm(s: str) -> str:
    s = unicodedata.normalize("NFKC", s)
    s = (s.replace("ﬁ", "fi").replace("ﬂ", "fl").replace("’", "'").replace("‘", "'")
         .replace("“", '"').replace("”", '"').replace("–", "-").replace("—", "-").replace("−", "-"))
    s = re.sub(r"-\s*\n\s*", "", s)           # de-hyphenate line breaks
    s = re.sub(r"\[\d+(,\s*\d+)*\]", "", s)    # numeric citation markers
    s = re.sub(r"[\s\-]+", "", s).lower()   # pdftotext drops/keeps hyphens inconsistently
    return s


def _quotes(note: str) -> list[str]:
    """Block quotes under a '## Verified quotes' heading. Adjacent `>` lines join."""
    m = re.search(r"^## Verified quotes\s*$(.*?)(?=^## |\Z)", note, re.M | re.S)
    if not m:
        return []
    out, cur = [], []
    for line in m.group(1).splitlines():
        if line.startswith(">"):
            cur.append(line[1:].strip())
        elif cur:
            out.append(" ".join(cur))
            cur = []
    if cur:
        out.append(" ".join(cur))
    cleaned = []
    for q in out:
        q = re.sub(r"\s*—\s*(p\.|§|sec|page).*$", "", q, flags=re.I)  # trailing locator
        q = q.strip().strip('"').strip("“”").strip()
        if q:
            cleaned.append(q)
    return cleaned


def cmd_verify_quotes(a):
    kb = KB(a.kb).require()
    refs = kb.load()
    bad_total = 0
    for r in _select(refs, a):
        note = kb.root / "notes" / f"{r['key']}.md"
        if not note.exists():
            continue
        r["note"] = f"notes/{note.name}"
        qs = _quotes(note.read_text())
        txt = kb.root / "text" / f"{r['key']}.txt"
        if not qs:
            r["quotes_verified"] = None
            print(f"  --   {r['key']}: no quotes")
            continue
        if not txt.exists():
            r["quotes_verified"] = None
            print(f"  ??   {r['key']}: {len(qs)} quote(s), no text/ to check against — hand-checked only")
            continue
        body = _qnorm(txt.read_text(errors="replace"))
        bad = []
        for q in qs:
            pieces = [p for p in re.split(r"\s*(?:\.\.\.|…|\[\.\.\.\])\s*", q) if p.strip()]
            if not all(_qnorm(p) in body for p in pieces):
                bad.append(q)
        r["quotes_verified"] = not bad
        bad_total += len(bad)
        print(f"  {'ok ' if not bad else 'BAD'}  {r['key']}: {len(qs) - len(bad)}/{len(qs)} quotes found in text")
        for q in bad:
            print(f"         not found: {q[:140]}")
    kb.save(refs)
    if bad_total:
        sys.exit(1)


