def _section(text: str, name: str) -> list[str]:
    m = re.search(rf"^## {re.escape(name)}\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        return []
    return [l.strip()[2:].strip() for l in m.group(1).splitlines() if l.strip().startswith(("- ", "* "))]


def cmd_keypoints(a):
    """Everything round N+1 is planned from: key points, open questions, leads,
    contradictions — grouped by trust so the plan leans on the solid ones."""
    kb = KB(a.kb).require()
    refs = [r for r in _select(kb.load(), a) if r["status"] == "read"]
    sections = ("Key points", "Contradictions and tensions", "Open questions", "Leads for next round")
    for sec in sections:
        print(f"\n## {sec}")
        for r in sorted(refs, key=lambda r: (r["trust"].get("tier") or 9, r["key"])):
            p = kb.root / "notes" / f"{r['key']}.md"
            if not p.exists():
                continue
            for item in _section(p.read_text(), sec):
                print(f"- [T{r['trust'].get('tier') or '?'} {r['key']}] {item}")
    print(f"\n({len(refs)} read notes from round {a.round or 'all'})")


def _bib(r: dict) -> str:
    kind = {"journal": "article", "conference": "inproceedings", "thesis": "phdthesis",
            "book": "book"}.get(r["venue_type"], "misc")
    fields = {"title": "{" + r["title"] + "}", "author": " and ".join(r["authors"]) or None,
              "year": r.get("year")}
    if kind == "article":
        fields["journal"] = r["venue"]
    elif kind == "inproceedings":
        fields["booktitle"] = r["venue"]
    if r.get("arxiv"):
        fields.update(eprint=r["arxiv"], archivePrefix="arXiv")
    if r.get("doi"):
        fields["doi"] = r["doi"]
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items() if v)
    return f"@{kind}{{{r['key']},\n{body}\n}}\n"


def cmd_render(a):
    kb = KB(a.kb).require()
    meta, refs, searches = kb.meta, kb.load(), kb.searches()
    today = dt.date.today().isoformat()
    by_status = {s: [r for r in refs if r["status"] == s] for s in STATUSES}
    read = by_status["read"]
    rounds = sorted({r["round"] for r in refs} | {s["round"] for s in searches})
    L = [f"# Literature review — {meta['topic']}", "",
         f"*Generated by `kb.py render` on {today}. Do not edit; edit `refs.jsonl` / `notes/` and re-render.*", ""]
    if meta.get("questions"):
        L += ["**Research questions**", ""] + [f"{i}. {q}" for i, q in enumerate(meta["questions"], 1)] + [""]
    L += ["| | " + " | ".join(STATUSES) + " | total |", "|---|" + "---|" * (len(STATUSES) + 1),
          "| records | " + " | ".join(str(len(by_status[s])) for s in STATUSES) + f" | {len(refs)} |", ""]
    L += ["## Rounds", "", "| round | queries | hits | new records | read |", "|---|---|---|---|---|"]
    for rn in rounds:
        ss = [s for s in searches if s["round"] == rn]
        L.append(f"| {rn} | {len(ss)} | {sum(s['hits'] for s in ss)} | {sum(s['new'] for s in ss)} | "
                 f"{sum(1 for r in read if r['round'] == rn)} |")
    L.append("")
    L += ["## Read, by trust tier", "",
          "Tier is the reader's judgement after reading (`trust-rubric.md`); `prior` is the metadata-only "
          "starting point. Quotes: ✅ every block quote found in the archived text, ❌ one is not, "
          "✋ no archived text — hand-checked only.", ""]
    for t, label in TIERS.items():
        rs = [r for r in read if r["trust"].get("tier") == t]
        if not rs:
            continue
        L += [f"### {label} ({len(rs)})", "", "| key | work | venue | year | rel | quotes | why this tier |",
              "|---|---|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda r: (-(r.get("relevance") or 0), r["key"])):
            q = {True: "✅", False: "❌", None: "✋" if r.get("note") else "—"}[r.get("quotes_verified")]
            link = f"[notes](notes/{r['key']}.md)" if (kb.root / "notes" / f"{r['key']}.md").exists() else ""
            L.append(f"| `{r['key']}` {link} | {r['title']} | {r['venue'] or r['venue_type']} | {r.get('year') or ''} "
                     f"| {r.get('relevance') if r.get('relevance') is not None else ''} | {q} "
                     f"| {r['trust'].get('rationale', '').replace('|', '/')} |")
        L.append("")
    untiered = [r for r in read if not r["trust"].get("tier")]
    if untiered:
        L += ["### ⚠ read but not yet tiered", ""] + [f"- `{r['key']}`" for r in untiered] + [""]
    inc = by_status["included"]
    if inc:
        L += ["## Included, not yet read", "", "| key | work | year | prior | cited by |", "|---|---|---|---|---|"]
        for r in sorted(inc, key=lambda r: -(r.get("cited_by") or 0)):
            L.append(f"| `{r['key']}` | {r['title']} | {r.get('year') or ''} | T{r['trust'].get('prior')} | {r.get('cited_by') or ''} |")
        L.append("")
    L += ["## Search log", "", "| round | source | query | hits | new |", "|---|---|---|---|---|"]
    for s in searches:
        L.append(f"| {s['round']} | {s['source']} | {s['query'].replace('|', '/')} | {s['hits']} | {s['new']} |")
    L.append("")
    (kb.root / "INDEX.md").write_text("\n".join(L))
    bib = [r for r in refs if r["status"] in ("read", "included")]
    (kb.root / "refs.bib").write_text("\n".join(_bib(r) for r in sorted(bib, key=lambda r: r["key"])))
    print(f"rendered INDEX.md ({len(refs)} records, {len(read)} read) and refs.bib ({len(bib)} entries)")


def cmd_status(a):
    kb = KB(a.kb).require()
    refs = kb.load()
    print(f"topic: {kb.meta['topic']}")
    for s in STATUSES:
        print(f"  {s:<13} {sum(1 for r in refs if r['status'] == s)}")
    read = [r for r in refs if r["status"] == "read"]
    problems = []
    for r in read:
        if not (kb.root / "notes" / f"{r['key']}.md").exists():
            problems.append(f"{r['key']}: status=read but no note")
        if not r["trust"].get("tier"):
            problems.append(f"{r['key']}: read but no tier")
        if r.get("quotes_verified") is False:
            problems.append(f"{r['key']}: a quote does not match the archived text")
        if not r.get("verified"):
            problems.append(f"{r['key']}: identifier never resolved")
    for p in problems:
        print("  ! " + p)
    print("consistent" if not problems else f"{len(problems)} problem(s)")


