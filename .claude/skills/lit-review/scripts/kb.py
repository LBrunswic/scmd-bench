#!/usr/bin/env python3
"""kb.py — the knowledge base behind /lit-review.

Stdlib only. One KB is one directory:

    <kb>/KB.json          topic, research questions, created date
    <kb>/refs.jsonl       one record per work — the source of truth
    <kb>/searches.jsonl   every query run: round, source, query, hits, new
    <kb>/notes/<key>.md   reading notes (template: ../templates/note.md)
    <kb>/pdf/<key>.pdf    archived full text
    <kb>/text/<key>.txt   pdftotext output, used by verify-quotes
    <kb>/rounds/          round-N-plan.md, round-N-summary.md (written by the agent)
    <kb>/INDEX.md         GENERATED by `render` — never edit by hand
    <kb>/refs.bib         GENERATED by `render`

Every network lookup goes to a public scholarly index (OpenAlex, arXiv, Crossref,
Semantic Scholar). Nothing identifying the user is sent.
"""
from __future__ import annotations

